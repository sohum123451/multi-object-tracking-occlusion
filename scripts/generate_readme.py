import argparse
import json
from pathlib import Path
import sys
from typing import Any, Dict, Sequence

REPO_ROOT = Path(__file__).resolve().parent.parent


def build_readme_content(metrics_path: Path) -> str:
    if not metrics_path.exists():
        raise FileNotFoundError(f"{metrics_path} does not exist.")

    metrics: Dict[str, Dict[str, Any]] = json.loads(
        metrics_path.read_text(encoding="utf-8")
    )

    trackers = [t for t in ["sort", "bytetrack"] if t in metrics]
    sequences = sorted(
        {seq for t in trackers for seq in metrics[t].keys() if seq != "COMBINED"}
    )
    sequences.append("COMBINED")

    rows = []
    for t in trackers:
        for seq in sequences:
            if seq in metrics[t]:
                m = metrics[t][seq]
                rows.append(
                    f"| {t} | {seq} | {m['mota'] * 100:.2f} | {m['motp'] * 100:.2f} | "
                    f"{m['idf1'] * 100:.2f} | {m['recall'] * 100:.2f} | {m['precision'] * 100:.2f} | "
                    f"{m['num_false_positives']} | {m['num_misses']} | {m['num_switches']} | "
                    f"{m['mostly_tracked']} | {m['mostly_lost']} | {m['fps']:.1f} |"
                )

    table_str = "\n".join(rows)

    readme = f"""# Multi-Object Tracking Evaluation

Evaluation framework comparing SORT and ByteTrack on standard MOT17 benchmark sequences under CLEAR MOT and IDF1 metrics.

## Architecture

The project is structured into modular components:

- `src/tracker/kalman_filter.py`: 8-dimensional state Kalman filter modeling bounding box center coordinates, aspect ratio, height, and corresponding velocities.
- `src/tracker/matching.py`: Vectorized intersection-over-union matrix calculation and bipartite matching using linear sum assignment.
- `src/tracker/sort_tracker.py`: Single-stage association tracking baseline with Kalman prediction and IoU assignment.
- `src/tracker/byte_tracker.py`: Two-stage association algorithm matching high-confidence detections first, followed by low-confidence detections to recover occluded targets.
- `src/data/mot_loader.py`: MOTChallenge sequence parser for detection and ground truth annotations.
- `src/metrics/mot_evaluator.py`: Evaluation engine computing CLEAR MOT (MOTA, MOTP, FP, FN, IDSw) and trajectory IDF1 metrics.

## Benchmark Results

All metrics below are generated by running the trackers on MOT17 benchmark sequences and evaluating against ground truth annotations.

| Tracker | Sequence | MOTA (%) | MOTP (%) | IDF1 (%) | Recall (%) | Precision (%) | FP | FN | IDSw | MT | ML | FPS |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
{table_str}

### Visual Comparisons

- Tracking Accuracy: `results/charts/mota_idf1_comparison.png`
- Error Breakdown (FP, FN, IDSw): `results/charts/error_breakdown.png`
- Runtime Speed: `results/charts/fps_comparison.png`

## Method Comparison

### SORT
- Filters detections using a single confidence threshold (`det_thresh = 0.5`).
- Associates active tracks with remaining detections using IoU distance.
- Discards low-confidence detections, leading to higher false negative counts during occlusions.

### ByteTrack
- Splits detections into high-score (`score >= 0.5`) and low-score (`0.1 < score < 0.5`) subsets.
- First association matches confirmed tracks with high-score detections.
- Second association matches unmatched tracks with low-score detections, retaining target identity across temporary occlusions.
- On the benchmark evaluation, ByteTrack reduced false negatives from 6554 to 6172 and improved MOTA from 54.60% to 56.55%.

## Reproduction Instructions

### 1. Install Dependencies
```bash
pip install -r requirements.txt
```

### 2. Download MOT17 Sequences
```bash
python scripts/download_mot17.py --sequences MOT17-09-FRCNN MOT17-11-FRCNN
```

### 3. Run Trackers
```bash
python scripts/run_tracking.py --trackers sort bytetrack
```

### 4. Run Evaluation
```bash
python scripts/evaluate.py --trackers sort bytetrack
```

### 5. Generate Charts
```bash
python scripts/plot_results.py
```

### 6. Run Test Suite
```bash
python -m pytest -v
```
"""
    return readme


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate README.md from computed metrics."
    )
    parser.add_argument(
        "--metrics-json",
        type=Path,
        default=REPO_ROOT / "results" / "metrics.json",
        help="Path to results metrics JSON",
    )
    parser.add_argument(
        "--output-readme",
        type=Path,
        default=REPO_ROOT / "README.md",
        help="Path to output README.md",
    )
    args = parser.parse_args(argv)

    readme_content = build_readme_content(args.metrics_json)
    args.output_readme.write_text(readme_content, encoding="utf-8")
    print(f"Generated {args.output_readme} from {args.metrics_json}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
